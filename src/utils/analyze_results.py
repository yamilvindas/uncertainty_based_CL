import h5py
import numpy as np
import argparse
from pathlib import Path
from sklearn.metrics import accuracy_score, balanced_accuracy_score, matthews_corrcoef, f1_score, roc_auc_score
import warnings

# Suppress sklearn undefined metric warnings for 0 division
warnings.filterwarnings('ignore', category=UserWarning)

def calculate_metrics(targets, preds, probs=None):
    """Computes a suite of metrics given true labels, hard predictions, and optionally probabilities."""
    metrics = {
        'Accuracy': accuracy_score(targets, preds),
        'Balanced_Acc': balanced_accuracy_score(targets, preds),
        'MCC': matthews_corrcoef(targets, preds),
        'F1_Macro': f1_score(targets, preds, average='macro', zero_division=0)
    }
    
    # Compute AUC-ROC if probabilities are provided
    if probs is not None:
        try:
            # Binary classification requires 1D array of probabilities for the positive class
            if probs.shape[1] == 2:
                metrics['ROC_AUC'] = roc_auc_score(targets, probs[:, 1])
            # Multiclass classification uses 'ovr' (One-vs-Rest)
            else:
                metrics['ROC_AUC'] = roc_auc_score(targets, probs, multi_class='ovr')
        except ValueError:
            # Fallback in case a batch only contains one class or ROC AUC fails
            pass
            
    return metrics

def analyze_h5_experiment(h5_path):
    """
    Reads an HDF5 file generated by CLTrainer, computes metrics across repetitions,
    and prints a summary mean ± std.
    """
    path = Path(h5_path)
    if not path.exists():
        print(f"[ERROR] File not found: {h5_path}")
        return

    # Dictionary to store raw metrics: results[phase][dataset][metric] = [rep1_val, rep2_val, ...]
    results = {}
    
    with h5py.File(path, 'r') as f:
        exp_name = f.attrs.get('experiment_name', 'Unknown Experiment')
        
        # Discover all Repetition groups (e.g., Rep_0, Rep_1)
        rep_keys = [k for k in f.keys() if k.startswith('Rep_')]
        if not rep_keys:
            print(f"[ERROR] No 'Rep_X' groups found in {h5_path}. Was the training completed?")
            return
            
        n_reps = len(rep_keys)
        
        # Iterate over all repetitions
        for rep_key in rep_keys:
            rep_group = f[rep_key]
            
            # Look only at the main evaluation phases
            phases = [k for k in rep_group.keys() if k.startswith('Phase_')]
            
            for phase in phases:
                if phase not in results:
                    results[phase] = {}
                    
                phase_group = rep_group[phase]
                # Datasets: Test_A, Test_B, Val_A, Ext_Test, etc.
                for dataset in phase_group.keys():
                    if dataset not in results[phase]:
                        results[phase][dataset] = {}
                    
                    preds = phase_group[dataset]['preds'][:]
                    targets = phase_group[dataset]['targets'][:]
                    
                    # Read probabilities if they were saved, otherwise return None
                    probs = phase_group[dataset]['probs'][:] if 'probs' in phase_group[dataset] else None
                    
                    metrics = calculate_metrics(targets, preds, probs)
                    
                    # Dynamically append metrics (allows ROC_AUC to be seamlessly included)
                    for metric_name, val in metrics.items():
                        if metric_name not in results[phase][dataset]:
                            results[phase][dataset][metric_name] = []
                        results[phase][dataset][metric_name].append(val)

    # ---------------------------------------------------------
    # PRINT SUMMARY
    # ---------------------------------------------------------
    print("=" * 65)
    print(f" EXPERIMENT REPORT: {exp_name}")
    print(f" Total Repetitions: {n_reps}")
    print("=" * 65)

    # Standard Phase Reporting
    phase_order = ['Phase_PreTraining', 'Phase_Post_Task_A', 'Phase_Post_Task_B']
    
    for phase in phase_order:
        if phase not in results: continue
        
        print(f"\n[{phase.replace('_', ' ').upper()}]")
        print("-" * 65)
        
        for dataset, metrics_dict in results[phase].items():
            # Focus output on Test sets to keep it readable, but you can remove this if condition to see Val sets too
            if 'Test' not in dataset: 
                continue
                
            print(f"  Dataset: {dataset}")
            for metric, values in metrics_dict.items():
                mean_val = np.mean(values)
                std_val = np.std(values)
                print(f"    - {metric:<15}: {mean_val:.4f} ± {std_val:.4f}")

    # ---------------------------------------------------------
    # CALCULATE FORGETTING (Task A degradation after Task B)
    # Forgetting = Performance(Post_Task_A) - Performance(Post_Task_B)
    # Higher forgetting means worse retention.
    # ---------------------------------------------------------
    if 'Phase_Post_Task_A' in results and 'Phase_Post_Task_B' in results:
        print("\n[CATASTROPHIC FORGETTING METRICS]")
        print(" (Calculated on Test_A: Post_Task_A metric minus Post_Task_B metric)")
        print("-" * 65)
        
        if 'Test_A' in results['Phase_Post_Task_A'] and 'Test_A' in results['Phase_Post_Task_B']:
            # Dynamically pull all metrics available to calculate forgetting
            available_metrics = results['Phase_Post_Task_A']['Test_A'].keys()
            
            for metric in available_metrics:
                if metric in results['Phase_Post_Task_B']['Test_A']:
                    # Get arrays of metrics across all reps
                    metric_post_A = np.array(results['Phase_Post_Task_A']['Test_A'][metric])
                    metric_post_B = np.array(results['Phase_Post_Task_B']['Test_A'][metric])
                    
                    # Element-wise forgetting (per repetition)
                    forgetting = metric_post_A - metric_post_B
                    
                    mean_forg = np.mean(forgetting)
                    std_forg = np.std(forgetting)
                    
                    print(f"    - {metric:<15} Forgetting: {mean_forg:+.4f} ± {std_forg:.4f}")
    
    print("\n" + "=" * 65)

if __name__ == "__main__":
    #====================================================================================================#
    #========================================= Argument Parsing =========================================#
    #====================================================================================================#
    # Construct the argument parser
    ap = argparse.ArgumentParser()
    # Add the arguments to the parser
    ap.add_argument("--h5_results_file", type=str, help="Path to the predictions.h5 file")
    args = vars(ap.parse_args())

    # Getting the results file
    h5_results_file = args['h5_results_file']

    #====================================================================================================#
    #========================================= Analyze rResults =========================================#
    #====================================================================================================#
    analyze_h5_experiment(h5_results_file)